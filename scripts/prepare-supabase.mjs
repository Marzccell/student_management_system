import { readFile, writeFile } from 'node:fs/promises'

// Generate one standalone SQL Editor script from the versioned base + migration.
// Preparing the file does not connect to Supabase or modify any database.
const root = new URL('../', import.meta.url)
const base = (await readFile(new URL('supabase/schema.sql', root), 'utf8'))
  .replace(
    /CREATE TABLE (assignments|study_sessions) \(/g,
    'CREATE TABLE IF NOT EXISTS $1 ('
  )
  .replace(
    /CREATE POLICY "([^"]+)"\s+ON (assignments|study_sessions)/g,
    (_, name, table) =>
      `DROP POLICY IF EXISTS "${name}" ON ${table};\nCREATE POLICY "${name}"\n  ON ${table}`
  )
const migration = await readFile(
  new URL('supabase/migrations/202610110001_campusflow_features.sql', root),
  'utf8'
)
const header = `-- StudyFlow database activation. Generated by npm run prepare:supabase.
-- Run the whole file in the SQL Editor of the Supabase project used by StudyFlow.
-- Creates missing base tables, applies the project/attachment upgrade, and sets
-- authenticated permissions. Does not delete tasks or login accounts.
-- Optional owner-scoped reset is a separate file: reset_my_data.sql.
BEGIN;
SET LOCAL search_path = public;
`
const sql =
  header +
  base +
  '\n' +
  migration.replace(/^BEGIN;\s*$/m, '').replace(/^COMMIT;\s*$/m, '') +
  `
GRANT SELECT, INSERT, UPDATE, DELETE ON public.assignments, public.study_sessions TO authenticated;
-- Ensure fresh databases have permissive owner policies as well as guards.
DROP POLICY IF EXISTS "studyflow_sessions_owner_guard" ON public.study_sessions;
CREATE POLICY "studyflow_sessions_owner_guard" ON public.study_sessions AS RESTRICTIVE
  FOR ALL TO public USING (user_id = (SELECT auth.uid())) WITH CHECK (user_id = (SELECT auth.uid()));
NOTIFY pgrst, 'reload schema';
COMMIT;
`
await writeFile(new URL('supabase/setup_workspace.sql', root), sql)
console.log(
  'Prepared supabase/setup_workspace.sql. No database changes have been applied.'
)
